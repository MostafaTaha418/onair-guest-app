  @override
  OnAirColors lerp(ThemeExtension<OnAirColors>? other, double t) {
    if (other is! OnAirColors) return this;
    return OnAirColors({
      for (final key in values.keys)
        key: Color.lerp(values[key], other.values[key], t)!,
    });
  }
